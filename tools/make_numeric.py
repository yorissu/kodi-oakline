"""Generate skin.oakline/xml/DialogNumeric.xml (number pad for PINs, times, IP addresses).

Kodi's ids: 10-19 the digits 0-9, 21 done, 23 backspace, 20 / 22 previous /
next field (for times and IP addresses), 4 the entered value, 1 the heading.

    python tools/make_numeric.py
"""
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "skin.oakline" / "xml" / "DialogNumeric.xml"
KEY, GAP = 120, 12
# rows of the pad; each cell is (id, label)
GRID = [[(11, "1"), (12, "2"), (13, "3")],
        [(14, "4"), (15, "5"), (16, "6")],
        [(17, "7"), (18, "8"), (19, "9")],
        [(20, "‹"), (10, "0"), (22, "›")]]
SIDE = [(23, "Delete"), (21, "Done")]


def key(kid, label, r, c):
    up = GRID[r - 1][c][0] if r else kid
    down = GRID[r + 1][c][0] if r < 3 else kid
    left = GRID[r][c - 1][0] if c else SIDE[min(r, 1)][0]
    right = GRID[r][c + 1][0] if c < 2 else SIDE[min(r, 1)][0]
    kind = "radiobutton" if kid in (20, 22) else "button"
    return f'''			<control type="{kind}" id="{kid}">
				<left>{c * (KEY + GAP)}</left>
				<top>{r * (KEY + GAP)}</top>
				<width>{KEY}</width>
				<height>{KEY}</height>
				<label>{"$NUMBER[" + label + "]" if label.isdigit() else label}</label>
				<include>KeyStyle</include>
				<onup>{up}</onup>
				<ondown>{down}</ondown>
				<onleft>{left}</onleft>
				<onright>{right}</onright>
			</control>
'''


def side(kid, label, i):
    return f'''			<control type="button" id="{kid}">
				<left>{3 * (KEY + GAP) + 24}</left>
				<top>{i * (KEY + GAP)}</top>
				<width>200</width>
				<height>{KEY}</height>
				<label>{label}</label>
				<include>KeyStyle</include>
				<onup>{SIDE[i - 1][0] if i else kid}</onup>
				<ondown>{SIDE[i + 1][0] if i < len(SIDE) - 1 else kid}</ondown>
				<onleft>{GRID[i][2][0]}</onleft>
				<onright>{GRID[i][0][0]}</onright>
			</control>
'''


def main():
    keys = "".join(key(kid, label, r, c) for r, row in enumerate(GRID) for c, (kid, label) in enumerate(row))
    keys += "".join(side(kid, label, i) for i, (kid, label) in enumerate(SIDE))
    width = 3 * (KEY + GAP) + 24 + 200 + 80
    xml = f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/make_numeric.py: edit that, not this file. -->
<window>
	<defaultcontrol always="true">11</defaultcontrol>
	<controls>
		<include>DialogScrim</include>
		<control type="group">
			<left>{(1920 - width) // 2}</left>
			<top>160</top>
			<include>DialogEase</include>
			<include content="Box">
				<param name="width" value="{width}" />
				<param name="height" value="760" />
				<param name="color" value="navy950" />
			</include>
			<include content="Box">
				<param name="width" value="{width}" />
				<param name="height" value="4" />
				<param name="color" value="wood" />
			</include>
			<control type="textbox" id="1">
				<left>40</left>
				<top>32</top>
				<width>{width - 80}</width>
				<height>40</height>
				<font>head</font>
				<textcolor>white</textcolor>
			</control>
			<include content="Box">
				<param name="left" value="40" />
				<param name="top" value="88" />
				<param name="width" value="{width - 80}" />
				<param name="height" value="76" />
				<param name="color" value="navy800" />
			</include>
			<control type="label" id="4">
				<left>64</left>
				<top>88</top>
				<width>{width - 128}</width>
				<height>76</height>
				<aligny>center</aligny>
				<font>input</font>
				<textcolor>white</textcolor>
			</control>
			<control type="group">
				<left>40</left>
				<top>196</top>
{keys}			</control>
		</control>
	</controls>
</window>
'''
    OUT.write_text(xml, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
