"""Generate skin.oakline/xml/DialogKeyboard.xml.

Kodi's keyboard dialog has fixed ids: 100-112, 120-132, 140-152, 160-172 are the
four key rows (Kodi sets their labels and hides unused keys), 300 done,
301 cancel, 8 backspace, 32 space, 302 shift, 303 caps, 304 symbols,
305/306 cursor, 309/310 layout/IME, 311 heading, 312 the edit field.
Too repetitive to keep by hand, so it is written from here.

    python tools/make_keyboard.py
"""
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "skin.oakline" / "xml" / "DialogKeyboard.xml"
ROWS = [100, 120, 140, 160]
COLS = 13
KEY_W, KEY_H, GAP = 96, 72, 8
LEFT, TOP = 160, 672
SIDE = [  # (id, label, column, row)
    (8, "Delete", 0, 0), (32, "Space", 0, 1), (302, "Shift", 0, 2), (303, "Caps", 0, 3),
    (300, "Done", 1, 0), (301, "Cancel", 1, 1), (304, "Symbols", 1, 2), (310, "", 1, 3),
]
SIDE_LEFT, SIDE_W = 1560, 150


def key(kid, up, down):
    return f'''				<control type="button" id="{kid}">
					<width>{KEY_W}</width>
					<include>KeyStyle</include>
					<onup>{up}</onup>
					<ondown>{down}</ondown>
				</control>
'''


def side(kid, label, col, row):
    above = [s for s in SIDE if s[2] == col and s[3] == row - 1]
    below = [s for s in SIDE if s[2] == col and s[3] == row + 1]
    other = [s for s in SIDE if s[2] == 1 - col and s[3] == row][0][0]
    left = f"{ROWS[row] + COLS - 1}" if col == 0 else other
    right = other if col == 0 else f"{ROWS[row]}"
    kind = "radiobutton" if kid in (302, 303, 304) else "button"
    lbl = f"<label>{label}</label>" if label else ""
    return f'''		<control type="{kind}" id="{kid}">
			<left>{SIDE_LEFT + col * (SIDE_W + GAP)}</left>
			<top>{TOP + row * (KEY_H + GAP)}</top>
			<width>{SIDE_W}</width>
			{lbl}
			<include>KeyStyle</include>
			<onup>{above[0][0] if above else kid}</onup>
			<ondown>{below[0][0] if below else kid}</ondown>
			<onleft>{left}</onleft>
			<onright>{right}</onright>
		</control>
'''


def main():
    rows = []
    for r, base in enumerate(ROWS):
        keys = "".join(key(base + c, (ROWS[r - 1] + c) if r else 312, (ROWS[r + 1] + c) if r < 3 else base + c)
                       for c in range(COLS))
        rows.append(f'''			<control type="grouplist">
				<top>{r * (KEY_H + GAP)}</top>
				<width>{COLS * (KEY_W + GAP)}</width>
				<height>{KEY_H}</height>
				<orientation>horizontal</orientation>
				<itemgap>{GAP}</itemgap>
				<onleft>{[s for s in SIDE if s[2] == 1 and s[3] == r][0][0]}</onleft>
				<onright>{[s for s in SIDE if s[2] == 0 and s[3] == r][0][0]}</onright>
{keys}			</control>
''')
    xml = f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/make_keyboard.py: edit that, not this file. -->
<window>
	<defaultcontrol always="true">100</defaultcontrol>
	<animation effect="fade" start="0" end="100" time="150">WindowOpen</animation>
	<animation effect="fade" start="100" end="0" time="100">WindowClose</animation>
	<controls>
		<control type="image">
			<width>1920</width>
			<height>1080</height>
			<texture colordiffuse="scrim">white.png</texture>
		</control>
		<include content="Box">
			<param name="top" value="500" />
			<param name="width" value="1920" />
			<param name="height" value="580" />
			<param name="color" value="navy950" />
		</include>
		<include content="Box">
			<param name="top" value="500" />
			<param name="width" value="1920" />
			<param name="height" value="4" />
			<param name="color" value="wood" />
		</include>
		<control type="label" id="311">
			<left>{LEFT}</left>
			<top>532</top>
			<width>1600</width>
			<height>30</height>
			<font>label</font>
			<textcolor>gray400</textcolor>
		</control>
		<include content="Box">
			<param name="left" value="{LEFT}" />
			<param name="top" value="572" />
			<param name="width" value="1600" />
			<param name="height" value="76" />
			<param name="color" value="navy800" />
		</include>
		<control type="edit" id="312">
			<left>{LEFT + 24}</left>
			<top>572</top>
			<width>1552</width>
			<height>76</height>
			<font>input</font>
			<textcolor>white</textcolor>
			<aligny>center</aligny>
			<texturefocus />
			<texturenofocus />
			<ondown>100</ondown>
		</control>

		<!-- key rows -->
		<control type="group">
			<left>{LEFT}</left>
			<top>{TOP}</top>
{"".join(rows)}		</control>

		<!-- function keys -->
{"".join(side(*s) for s in SIDE)}
		<!-- unused here, but Kodi looks for them -->
		<control type="button" id="305"><visible>false</visible></control>
		<control type="button" id="306"><visible>false</visible></control>
		<control type="button" id="309"><visible>false</visible></control>
		<control type="button" id="307"><visible>false</visible></control>
	</controls>
</window>
'''
    OUT.write_text(xml, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
