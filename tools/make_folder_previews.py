"""Generate preview frames for folders ("shows"):

    python tools/make_folder_previews.py

writes skin.oakline/xml/Includes_Folders.xml and the folder-preview part of
skin.oakline/xml/Timers.xml.

Kodi gives a folder no thumbnail of its own (only folder.jpg / poster.jpg if
present). To show a folder with a frame from its first video:
  1. a hidden list ("loader") per item position lists that folder's contents
     (a layout can't hold a list, so loader k serves item k of a row/view);
  2. a skin timer per loader notices when the loader's folder changes and
     copies the first frame into Window(home).Property(oakprev<row><k>);
  3. the tile reads the property for its position (ListItem.CurrentItem).
Step 2 is needed because inside a list layout Kodi answers
Container(x).ListItemAbsolute(n).* for the layout's own item, so a tile can't
read the loader directly; window properties don't have that problem.

Rows (containers) that get previews:
  Home   Container(8600)   Home: the videos folder A-Z      (10)
  Recent Container(8610)   Home: recently added             (10)
  Movies Container.        Movies window (the current view) (24)
"""
import re
from pathlib import Path

XML = Path(__file__).resolve().parent.parent / "skin.oakline" / "xml"
OUT = XML / "Includes_Folders.xml"
TIMERS = XML / "Timers.xml"
BEGIN, END = "<!-- folder previews: generated by tools/make_folder_previews.py -->", "<!-- end of folder previews -->"

SOURCES = [
    # name, container prefix, loader id base, how many, extra condition for loading
    ("Home", "Container(8600).", 8700, 10, ""),
    ("Recent", "Container(8610).", 8720, 10, ""),
    ("Movies", "Container.", 8800, 24, " + [String.IsEmpty(Container.Content) | Container.Content(files)] + !String.StartsWith(Container.FolderPath,plugin://)"),
]


def loader_path_var(name, prefix, k, extra):
    i = k - 1
    return f'''	<variable name="FolderLoad{name}{k}">
		<value condition="{prefix}ListItemAbsolute({i}).IsFolder + !{prefix}ListItemAbsolute({i}).IsParentFolder{extra}">$INFO[{prefix}ListItemAbsolute({i}).FolderPath]</value>
		<value></value>
	</variable>
'''


def frame_var(name, base, k):
    """First frame in loader k (outside any layout, so the loader can be read)."""
    c = f"Container({base + k})"
    vals = [f'		<value condition="!String.IsEmpty({c}.ListItemAbsolute({j}).Art(thumb))">$INFO[{c}.ListItemAbsolute({j}).Art(thumb)]</value>'
            for j in (0, 1, 2)]  # the first entries can be subfolders (seasons) without a frame
    return f'	<variable name="FolderFrame{name}{k}">\n' + "\n".join(vals) + '\n		<value></value>\n	</variable>\n'


def preview_var(name, count):
    out = [f'	<variable name="FolderPreview{name}">']
    for k in range(1, count + 1):
        out.append(f'		<value condition="String.IsEqual(ListItem.CurrentItem,{k})">$INFO[Window(home).Property(oakprev{name}{k})]</value>')
    out.append('		<value></value>')
    out.append('	</variable>')
    return "\n".join(out) + "\n"


def count_var(name, base, count):
    out = [f'	<variable name="FolderCount{name}">']
    for k in range(1, count + 1):
        c = f"Container({base + k})"
        out.append(f'		<value condition="String.IsEqual(ListItem.CurrentItem,{k}) + Integer.IsEqual({c}.NumItems,1)">  ·  1 video</value>')
        out.append(f'		<value condition="String.IsEqual(ListItem.CurrentItem,{k}) + Integer.IsGreater({c}.NumItems,1)">$INFO[{c}.NumItems,  ·  , videos]</value>')
    out.append('		<value></value>')
    out.append('	</variable>')
    return "\n".join(out) + "\n"


def loaders_include(name, base, count):
    out = [f'	<!-- hidden lists with the contents of the folders in {name} (one per position) -->',
           f'	<include name="FolderLoaders{name}">']
    for k in range(1, count + 1):
        out.append(f'''		<control type="list" id="{base + k}">
			<left>-4000</left>
			<width>10</width>
			<height>10</height>
			<itemlayout width="10" height="10" />
			<focusedlayout width="10" height="10" />
			<content target="videos" sortby="label">$VAR[FolderLoad{name}{k}]</content>
		</control>''')
    out.append('	</include>')
    return "\n".join(out) + "\n"


def timers():
    out = []
    for name, _prefix, base, count, _extra in SOURCES:
        for k in range(1, count + 1):
            c = f"Container({base + k})"
            key = f"{name}{k}"
            # change signal: the loader's first entry (Container(id).FolderPath is empty for plain lists)
            cond = f"!{c}.IsUpdating + !String.IsEqual({c}.ListItemAbsolute(0).FileNameAndPath,Window(home).Property(oakdir{key}))"
            out.append(f'''	<timer>
		<name>oak_preview_{key}</name>
		<start reset="true">{cond}</start>
		<onstart>SetProperty(oakdir{key},$INFO[{c}.ListItemAbsolute(0).FileNameAndPath],home)</onstart>
		<onstart>SetProperty(oakprev{key},$VAR[FolderFrame{key}],home)</onstart>
		<stop>![{cond}]</stop>
	</timer>''')
    return "\n".join(out)


def main():
    parts = ['<?xml version="1.0" encoding="UTF-8"?>',
             '<!-- Generated by tools/make_folder_previews.py: do not edit by hand. -->',
             '<includes>']
    for name, prefix, base, count, extra in SOURCES:
        parts.append(loaders_include(name, base, count))
        for k in range(1, count + 1):
            parts.append(loader_path_var(name, prefix, k, extra))
            parts.append(frame_var(name, base, k))
        parts.append(preview_var(name, count))
        parts.append(count_var(name, base, count))
    parts.append('</includes>\n')
    OUT.write_text("\n".join(parts), encoding="utf-8", newline="\n")

    t = TIMERS.read_text(encoding="utf-8")
    block = f"\t{BEGIN}\n{timers()}\n\t{END}\n"
    if BEGIN in t:
        t = re.sub(re.escape("\t" + BEGIN) + ".*?" + re.escape(END) + "\n", lambda m: block, t, flags=re.S)
    else:
        t = t.replace("</timers>", block + "</timers>")
    TIMERS.write_text(t, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.name} and {TIMERS.name}: {sum(s[3] for s in SOURCES)} loaders")


if __name__ == "__main__":
    main()
